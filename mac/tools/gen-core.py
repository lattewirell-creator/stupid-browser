#!/usr/bin/env python3
"""Generate mac/core/core-gen.js from the Electron app's src/main.js (and friends): the settings
defaults, validation, search engines, sidebar apps… copied verbatim, so the Mac version always
behaves exactly like the Electron version. Run by mac/build.sh; never edit core-gen.js by hand."""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'src')
OUT = os.path.join(HERE, '..', 'core', 'core-gen.js')

def read(name):
    return open(os.path.join(SRC, name), encoding='utf-8').read()

def block(text, start):
    """The whole top-level statement starting at `start` (ends at ';' or a closing '}' line).
    Skips strings, comments and regex literals so brackets inside them don't count."""
    i = text.index(start)
    depth, j, seen = 0, i, False
    while j < len(text):
        c = text[j]
        if c in '{([':
            depth += 1; seen = True
        elif c in '})]':
            depth -= 1
        elif c in "'\"`":
            q = c; j += 1
            while text[j] != q:
                j += 2 if text[j] == '\\' else 1
        elif c == '/' and text[j + 1] == '/':
            while text[j] != '\n': j += 1
            continue
        elif c == '/' and text[j + 1] == '*':
            j = text.index('*/', j + 2) + 1
        elif c == '/' and (text[:j].rstrip()[-1:] in '(,=:[!&|?{};+-*%<>~^' or text[:j].rstrip().endswith('return')):
            j += 1; in_class = False
            while in_class or text[j] != '/':
                if text[j] == '\\': j += 1
                elif text[j] == '[': in_class = True
                elif text[j] == ']': in_class = False
                j += 1
        if depth == 0 and c == ';':
            return text[i:j + 1]
        if depth == 0 and seen and c == '\n' and text[i:j].rstrip()[-1:] == '}':
            return text[i:j].rstrip()
        j += 1
    raise ValueError(start)

main = read('main.js')
parts = [block(main, s) for s in (
    'const DEFAULT_BOTS = [', 'const SEARCH_ENGINES = {', 'const DEFAULT_SETTINGS = () => (', 'const DEFAULT_SIDEBAR = [',
    'const DEFAULT_LAUNCHER = [', 'const INTERNAL_PAGES = [', 'const PERM_KINDS = [', 'const FONT_SIZES = {',
    'const WIDGET_TYPES = [', 'const num = (v, lo, hi) =>', 'const cleanWidgets = (list) =>', 'const cleanLauncher = (list) =>',
    'const cleanEq = (eq) => {', 'function cleanPatch(patch) {', 'function searchUrlFor(s) {')]
# Helpers and whole IPC handlers that are plain logic, reused verbatim (core.js provides store, broadcast,
# handle, setSettings' side effects and the other Electron stand-ins they use).
parts += [block(main, s) for s in (
    'const getSettings = () =>', 'function setSettings(patch) {', 'function publicSettings() {', 'function getBookmarks() {',
    'const getBots = () =>', 'const getHistory = () =>', 'const getSitePerms = () =>', 'const getPasswords = () =>', 'const getDownloads = () =>',
    'function addHistory(url, title) {', 'function titleHistory(url, title) {', 'function suggest(q, limit = 7) {')]
PURE = ['settings:get', 'settings:set', 'settings:reset', 'bookmarks:get', 'bookmarks:set', 'bots:get', 'bots:set', 'bots:defaults',
        'sidebar:get', 'sidebar:set', 'sidebar:defaults', 'launcher:get', 'launcher:set', 'launcher:defaults', 'background:get', 'background:set',
        'widgets:get', 'widgets:set', 'history:suggest', 'history:query', 'history:delete', 'perms:get', 'perms:set', 'adblock:set', 'adblock:get', 'eq:get']
parts += [block(main, f"handle('{ch}'") for ch in PURE]
code = '\n'.join(parts).replace("app.getPath('downloads')", 'HOST_INFO.downloads')

bm = read('buddy-main.js')
code += '\n' + '\n'.join(block(bm, s) for s in ('const PROVIDERS = {', 'const CLAUDE_MODELS = {', 'const SYSTEM_TEXT = `', 'const MAX_TURNS = ', 'const validBase = (u) =>'))

ib = read('import-bookmarks.js')
code += '\n' + '\n'.join(block(ib, s) for s in ('const decodeEntities = (s) =>', 'function readHtml(text) {', 'function parseCsv(text) {'))

rw = read('rewind-main.js')
code += '\n' + '\n'.join(block(rw, s) for s in ('const MAX_ITEMS = ', 'const SENSITIVE = '))

open(OUT, 'w', encoding='utf-8').write(
    "// GENERATED by mac/tools/gen-core.py from the Electron app's src/*.js. Do not edit by hand.\n"
    "'use strict';\nvar HOST_INFO = { downloads: '' };\n" + code + '\n')
print('wrote', os.path.relpath(OUT), len(code), 'chars')
