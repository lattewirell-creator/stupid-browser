# Page helpers, generated from the Electron preloads so they behave exactly the same:
#  gen-media.js  (page's own world): the music island's media helper + equalizer (media-preload.js)
#  gen-select.js (isolated world): highlighted text → "Ask Buddy", mouse back/forward buttons (select-preload.js)
#  gen-pw.js     (isolated world, not in private windows): save and fill passwords (page-preload.js)
