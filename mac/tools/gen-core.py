#!/usr/bin/env python3
"""Generate mac/core/core-gen.js from the Electron app's src/main.js (and friends): the settings
defaults, validation, search engines, sidebar apps… copied verbatim, so the Mac version always
behaves exactly like the Electron version. Run by mac/build.sh; never edit core-gen.js by hand."""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'src')
OUT = os.path.join(HERE, '..', 'core', 'core-gen.js')

def read(name):
    return open(os.path.join(SRC, name), encoding='utf-8').read()

def block(text, start):
    """The whole top-level statement starting at `start` (ends at ';' or a closing '}' line).
    Skips strings, comments and regex literals so brackets inside them don't count."""
    i = text.index(start)
    depth, j, seen = 0, i, False
    while j < len(text):
        c = text[j]
        if c in '{([':
            depth += 1; seen = True
        elif c in '})]':
            depth -= 1
        elif c in "'\"`":
            q = c; j += 1
            while text[j] != q:
                j += 2 if text[j] == '\\' else 1
        elif c == '/' and text[j + 1] == '/':
            while text[j] != '\n': j += 1
            continue
        elif c == '/' and text[j + 1] == '*':
            j = text.index('*/', j + 2) + 1
        elif c == '/' and (text[:j].rstrip()[-1:] in '(,=:[!&|?{};+-*%<>~^' or text[:j].rstrip().endswith('return')):
            j += 1; in_class = False
            while in_class or text[j] != '/':
                if text[j] == '\\': j += 1
                elif text[j] == '[': in_class = True
                elif text[j] == ']': in_class = False
                j += 1
        if depth == 0 and c == ';':
            return text[i:j + 1]
        if depth == 0 and seen and c == '\n' and text[i:j].rstrip()[-1:] == '}':
            return text[i:j].rstrip()
        j += 1
    raise ValueError(start)

