// Builds src/action-preload.js from electron-chrome-extensions' toolbar-button module. The browser window's preloads
// run sandboxed and can't require() files from node_modules, so the module is copied in whole and started here.
// Run after updating electron-chrome-extensions: node scripts/gen-action-preload.js
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(require.resolve('electron-chrome-extensions/browser-action'), 'utf8');
const ver = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'node_modules', 'electron-chrome-extensions', 'package.json'), 'utf8')).version;
const out = `'use strict';
// GENERATED by scripts/gen-action-preload.js from electron-chrome-extensions ${ver} (MIT, (c) Samuel Maddock) — do not edit.
// Gives the browser window the <browser-action-list> element: your extensions' toolbar buttons and their popups.
if (location.protocol === 'file:' && /\\/index\\.html$/.test(location.pathname)) (() => {
const module = { exports: {} }; const exports = module.exports;
${src}
module.exports.injectBrowserAction();
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'action-preload.js'), out);
console.log('wrote src/action-preload.js from', ver);
